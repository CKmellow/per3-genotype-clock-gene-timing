"""Assemble the final deliverable notebook from the stage notebooks.

    python scripts/build_notebook.py                 # -> notebooks/PER3_clock_timing.ipynb
    python scripts/build_notebook.py --execute       # also run it top-to-bottom (needs network)
    python scripts/build_notebook.py -o other.ipynb

Rules:
* stage notebooks ``notebooks/stages/0[1-8]_*.ipynb`` are concatenated in order;
* every cell tagged ``bootstrap`` is dropped, and **one** bootstrap cell (from the
  first stage) is inserted at the top, after a title cell;
* outputs from the stage notebooks are cleared (they should already be empty);
* the result is validated with nbformat.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
STAGES_DIR = ROOT / "notebooks" / "stages"
DEFAULT_OUT = ROOT / "notebooks" / "PER3_clock_timing.ipynb"
STAGE_RE = re.compile(r"^0([1-8])_.+\.ipynb$")

TITLE = """# Does PER3 genotype shift the timing of clock-gene expression in human blood?

**Research question.** Does PER3 genotype (4/4 vs 5/5) shift the time of day at which the clock genes PER2, PER3 and NR1D1 reach peak expression in human blood?

Group project notebook (GEO GSE39445). Generated by `scripts/build_notebook.py` from `notebooks/stages/`. Do not edit it by hand; edit the stage notebooks.

Run the first cell (Colab bootstrap), then *Runtime → Run all*.

**Stages:** 1 Question & objectives · 2 Data acquisition · 3 Preprocessing & QC · 4 EDA · 5 Core analysis · 6 Biological interpretation · 7 Machine learning · 8 Conclusions"""


def stage_paths(stages_dir: Path = STAGES_DIR) -> list[Path]:
    paths = sorted(p for p in stages_dir.glob("*.ipynb") if STAGE_RE.match(p.name))
    nums = [int(STAGE_RE.match(p.name).group(1)) for p in paths]
    if nums != list(range(1, 9)):
        raise SystemExit(f"Expected stages 01..08 exactly once, found {[p.name for p in paths]}")
    return paths


def is_bootstrap(cell) -> bool:
    return "bootstrap" in cell.get("metadata", {}).get("tags", [])


def build(stages_dir: Path = STAGES_DIR) -> nbformat.NotebookNode:
    paths = stage_paths(stages_dir)
    first = nbformat.read(paths[0], as_version=4)
    boots = [c for c in first.cells if is_bootstrap(c)]
    if not boots:
        raise SystemExit(f"{paths[0].name} has no cell tagged 'bootstrap'")

    out = nbformat.v4.new_notebook()
    out.metadata = {
        "kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
        "language_info": {"name": "python"},
        "colab": {"provenance": [], "name": "PER3_clock_timing.ipynb"},
    }
    boot = nbformat.v4.new_code_cell(boots[0].source)
    boot.metadata["tags"] = ["bootstrap"]
    out.cells = [nbformat.v4.new_markdown_cell(TITLE), boot]

    for p in paths:
        nb = nbformat.read(p, as_version=4)
        for cell in nb.cells:
            if is_bootstrap(cell):
                continue
            if cell.cell_type == "code":
                new = nbformat.v4.new_code_cell(cell.source)
            elif cell.cell_type == "markdown":
                new = nbformat.v4.new_markdown_cell(cell.source)
            else:
                new = nbformat.v4.new_raw_cell(cell.source)
            tags = [t for t in cell.get("metadata", {}).get("tags", []) if t != "bootstrap"]
            if tags:
                new.metadata["tags"] = tags
            out.cells.append(new)
    # deterministic cell ids so rebuilding an unchanged notebook gives an identical file
    for n, cell in enumerate(out.cells):
        cell["id"] = f"cell-{n:03d}"
    nbformat.validate(out)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--stages-dir", type=Path, default=STAGES_DIR)
    ap.add_argument("--execute", action="store_true", help="execute the notebook with nbclient")
    ap.add_argument("--timeout", type=int, default=1800, help="per-cell timeout (s) with --execute")
    args = ap.parse_args(argv)

    nb = build(args.stages_dir)
    if args.execute:
        from nbclient import NotebookClient

        NotebookClient(nb, timeout=args.timeout, kernel_name="python3",
                       resources={"metadata": {"path": str(args.output.parent)}}).execute()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    nbformat.write(nb, args.output)
    print(f"Wrote {args.output} ({len(nb.cells)} cells{', executed' if args.execute else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
