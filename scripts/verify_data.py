"""Verify the GSE39445 inputs and write ``results/tables/data_verification.md``.

Usage::

    python scripts/verify_data.py              # includes series-matrix checks (downloads ~100 MB once)
    python scripts/verify_data.py --offline    # skip the series matrix

Also writes ``results/tables/timepoints_per_subject.csv`` and
``results/tables/sample_anomalies.csv``.
"""

from __future__ import annotations

import argparse
import hashlib
from datetime import date

import numpy as np
import pandas as pd

from per3clock import config, data


def sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def md_table(df: pd.DataFrame, index: bool = False) -> str:
    d = df.reset_index() if index else df
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in d.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def timing_anomalies(meta: pd.DataFrame) -> pd.DataFrame:
    """Flag samples whose timing annotations are internally inconsistent.

    For each subject × condition the protocol implies:
    * hours_awake = 7.5 + 3 * (timepoint_n - 1)
    * (clock_time_h - circadian_phase_h) mod 24 is ~constant (the clock time of
      circadian phase 0), so we flag samples deviating > 1 h from the series median.
    * consecutive samples ~3 h apart in clock time.
    """
    rows = []
    for (subj, cond), g in meta.groupby(["subject", "condition_code"]):
        g = g.sort_values("timepoint_n")
        ref = (g["clock_time_h"] - g["circadian_phase_h"]) % 24
        # circular median-ish: centre on the first value to avoid wrap problems
        centred = ((ref - ref.iloc[0] + 12) % 24) - 12
        dev = centred - centred.median()
        exp_awake = 7.5 + 3 * (g["timepoint_n"] - 1)
        # Sampling began in the evening and runs ~40 h, so add 24 h each time the
        # clock wraps past midnight to get a monotonic elapsed clock time.
        unwrapped = g["clock_time_h"].to_numpy().copy()
        for i in range(1, len(unwrapped)):
            while unwrapped[i] < unwrapped[i - 1]:
                unwrapped[i:] += 24
        gap = np.diff(unwrapped, prepend=np.nan)
        tp_gap = g["timepoint_n"].diff().to_numpy()
        for i, (_, r) in enumerate(g.iterrows()):
            issues = []
            if abs(r.hours_awake - exp_awake.iloc[i]) > 0.01:
                issues.append(f"hours_awake {r.hours_awake} != expected {exp_awake.iloc[i]}")
            if abs(dev.iloc[i]) > 1:
                issues.append(
                    f"clock_time - circadian_phase differs from series median by {dev.iloc[i]:+.2f} h"
                )
            if i > 0 and not np.isnan(gap[i]):
                exp_gap = 3 * tp_gap[i]
                if abs(gap[i] - exp_gap) > 0.5:
                    issues.append(
                        f"clock-time gap from previous sample {gap[i]:.2f} h (expected ~{exp_gap:.0f} h)"
                    )
            if issues:
                rows.append(
                    {
                        "sample_id": r.sample_id,
                        "subject": subj,
                        "condition": cond,
                        "timepoint": r.timepoint,
                        "clock_time": r.clock_time,
                        "circadian_phase_h": r.circadian_phase_h,
                        "hours_awake": r.hours_awake,
                        "issue": "; ".join(issues),
                    }
                )
    return pd.DataFrame(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true", help="skip series-matrix checks")
    args = ap.parse_args()
    config.ensure_dirs()
    out: list[str] = []
    w = out.append

    w("# Data verification report: GSE39445\n")
    w(f"Generated by `scripts/verify_data.py` on {date.today().isoformat()}. "
      "Re-run it after any change to `data/raw/` or `per3clock.data`.\n")

    # ---- files --------------------------------------------------------------------
    w("## 1. Input files\n")
    files = [config.METADATA_CSV, config.CLOCK_GENES_CSV, config.PROBE_ANNOTATION_CSV,
             config.SOFT_SAMPLES_TXT]
    ft = pd.DataFrame(
        {
            "file": [f"data/raw/{p.name}" for p in files],
            "bytes": [p.stat().st_size for p in files],
            "sha256": [sha256(p)[:16] + "…" for p in files],
        }
    )
    w(md_table(ft) + "\n")

    # ---- metadata -----------------------------------------------------------------
    meta = data.load_metadata()
    raw_meta = pd.read_csv(config.METADATA_CSV, dtype=str, keep_default_na=False)
    subj = meta.drop_duplicates("subject")
    w("## 2. Samples, subjects, genotypes\n")
    w(f"- Samples in metadata CSV: **{len(meta)}** (unique sample_id: {meta.sample_id.nunique()})")
    w(f"- Subjects: **{meta.subject.nunique()}**; genotype split (subjects): "
      + ", ".join(f"{k}: **{v}**" for k, v in subj.per3_genotype.value_counts().sort_index().items()))
    w("- Samples per condition: "
      + ", ".join(f"{k}: {v}" for k, v in meta.sleep_condition.value_counts().sort_index().items()))
    w(f"- Blank subject in source CSV: {(raw_meta.subject == '').sum()}; blank genotype: "
      f"{(raw_meta.per3_genotype == '').sum()} (all recovered; 0 blanks after `load_metadata()`)")
    w(f"- Subjects with conflicting genotypes across samples: "
      f"{int((meta.groupby('subject').per3_genotype.nunique() > 1).sum())}\n")

    # ---- recovered ----------------------------------------------------------------
    soft = data.load_soft_samples()
    rec = meta[meta.is_recovered].copy()
    rec["GEO genotype (SOFT key `genotype`)"] = (
        soft.loc[rec.sample_id, "genotype"].str.replace("\\", "/", regex=False).to_numpy()
    )
    rec["agrees"] = rec["GEO genotype (SOFT key `genotype`)"] == rec.per3_genotype
    w("## 3. Recovered samples (blank subject/genotype in source CSV)\n")
    w("These 11 samples were added to GEO later (GSM1526434–GSM1526444). Their GEO "
      "records have **no `subject` characteristic**, and genotype is stored under the "
      "key `genotype` instead of `genotype/variation`, so the original CSV parse left "
      "both blank. `load_metadata()` recovers the subject from the title "
      "(`AF0033_SE_T2` → AF0033, SE, T2) and the genotype from that subject's other "
      "samples. The recovered genotype is then cross-checked against GEO's own "
      "`genotype` field.\n")
    w(md_table(rec[["sample_id", "title", "subject", "condition_code", "timepoint",
                    "per3_genotype", "GEO genotype (SOFT key `genotype`)", "agrees"]]) + "\n")

    # ---- SOFT consistency -----------------------------------------------------------
    s = soft.loc[meta.sample_id]
    checks = {
        "title": (s["title"].to_numpy() == meta.title.to_numpy()).all(),
        "clock_time": (s["timesampletaken"].to_numpy() == meta.clock_time.to_numpy()).all(),
        "circadian_phase_h": (s["circadianphase"].astype(float).to_numpy()
                              == meta.circadian_phase_h.to_numpy()).all(),
        "hours_awake": (s["hoursawake"].astype(float).to_numpy()
                        == meta.hours_awake.to_numpy()).all(),
        "sleep_condition": (s["sleepprotocol"].to_numpy() == meta.sleep_condition.to_numpy()).all(),
    }
    gt_soft = s["genotype/variation"].fillna(s["genotype"]).str.replace("\\", "/", regex=False)
    checks["per3_genotype"] = (gt_soft.to_numpy() == meta.per3_genotype.to_numpy()).all()
    subj_soft = s["subject"].dropna()
    checks["subject (where present)"] = (
        subj_soft.to_numpy() == meta.set_index("sample_id").loc[subj_soft.index, "subject"].to_numpy()
    ).all()
    w("## 4. Metadata CSV vs GEO SOFT (`data/raw/GSE39445.txt`)\n")
    w(f"SOFT file contains {len(soft)} samples.\n")
    w(md_table(pd.DataFrame({"field": list(checks), "all 438 agree": list(checks.values())})) + "\n")

    # ---- clock CSV coverage ---------------------------------------------------------
    wide = pd.read_csv(config.CLOCK_GENES_CSV)
    pmap = data.clock_probe_columns(wide.columns)
    w("## 5. Clock-gene CSV coverage\n")
    w(f"- Rows: **{len(wide)}** samples. The last line has no trailing newline, so `wc -l` "
      f"reports {len(wide)} (header + {len(wide) - 1}), which undercounts the data rows by one.")
    w(f"- Samples in metadata but not clock CSV: {sorted(set(meta.sample_id) - set(wide.sample_id))}; "
      f"in clock CSV but not metadata: {sorted(set(wide.sample_id) - set(meta.sample_id))}")
    w(f"- Probe columns: {len(pmap)} for {len({g for g, _ in pmap.values()})} genes; "
      f"blank expression cells: {int(wide[list(pmap)].isna().sum().sum())}")
    vals = wide[list(pmap)].to_numpy()
    w(f"- Value range {vals.min():.2f}–{vals.max():.2f} (log2 scale; see §7 for the full matrix)")
    annot = data.load_probe_annotation()
    pt = pd.DataFrame(
        [{"column": c, "probe_id": p, "PROBE_NAME": annot.loc[p, "PROBE_NAME"],
          "annotated symbol": annot.loc[p, "GENE_SYMBOL"]} for c, (g, p) in pmap.items()]
    )
    w("\n" + md_table(pt) + "\n")
    meta_cols = ["subject", "per3_genotype", "sleep_condition", "hours_awake", "clock_time",
                 "circadian_phase_h"]
    wm = wide.set_index("sample_id")[meta_cols].astype(str)
    rm = raw_meta.set_index("sample_id").loc[wm.index, meta_cols].replace({"": "nan"})
    diff = int((wm != rm).sum().sum())
    w(f"Metadata columns duplicated in the clock CSV differ from the metadata CSV in {diff} cells "
      "(the same 11 blank subject/genotype pairs = 22 cells are expected).\n")

    # ---- timepoints ---------------------------------------------------------------
    w("## 6. Timepoints per subject and condition\n")
    tp = (meta.pivot_table(index=["subject", "per3_genotype"], columns="condition_code",
                           values="sample_id", aggfunc="count", fill_value=0)
          .rename(columns={"SE": "n_SE", "SR": "n_SR"}))
    allt = set(range(1, 11))
    for code in ("SE", "SR"):
        miss = (meta[meta.condition_code == code].groupby("subject").timepoint_n
                .agg(lambda x: ",".join(f"T{t}" for t in sorted(allt - set(x)))))
        tp[f"missing_{code}"] = miss.reindex(tp.index.get_level_values(0)).fillna("all").to_numpy()
    tp.to_csv(config.TABLES_DIR / "timepoints_per_subject.csv")
    w("Saved to `results/tables/timepoints_per_subject.csv`.\n")
    w(md_table(tp, index=True) + "\n")
    w("- SE-only subjects: " + ", ".join(tp[tp.n_SR == 0].index.get_level_values(0)))
    w("- SR-only subjects: " + ", ".join(tp[tp.n_SE == 0].index.get_level_values(0)) + "\n")

    w("### Shared default sample set (`analysis_samples`)\n")
    w("Decided 2026-11-11 (issue #10). **Default:** Sleep Extension, subjects with ≥6 timepoints, "
      "because a 3-parameter cosinor copes with one or two missing points and stricter filtering "
      "mainly costs power. **`strict=True`** applies the original authors' rule as a sensitivity "
      "analysis. **`for_phase_analysis=True`** also drops AF0182 in SE, whose `circadian_phase_h` "
      "labels are inconsistent (§8); AF0182 stays in clock-time analyses because its clock times "
      "are real. Part 2 (#2) checks these defaults.\n")
    rows = []
    variants = [
        ("Sleep Extension", {}, "default (main analysis)"),
        ("Sleep Extension", {"strict": True}, "strict=True (sensitivity)"),
        ("Sleep Extension", {"for_phase_analysis": True}, "for_phase_analysis=True"),
        ("Sleep Extension", {"strict": True, "for_phase_analysis": True}, "strict + phase"),
        ("Sleep Restriction", {}, "default (SR sensitivity)"),
        ("Sleep Restriction", {"strict": True}, "strict=True"),
    ]
    for cond, kw, label in variants:
        a, ex = data.analysis_samples(cond, metadata=meta, return_exclusions=True, **kw)
        sp = a.drop_duplicates("subject").per3_genotype.value_counts()
        rows.append({"condition": cond, "call": label, "subjects": a.subject.nunique(),
                     "4/4": sp.get("4/4", 0), "5/5": sp.get("5/5", 0), "samples": len(a),
                     "excluded": ", ".join(ex.subject)})
    w(md_table(pd.DataFrame(rows)) + "\n")
    _, ex = data.analysis_samples(metadata=meta, strict=True, for_phase_analysis=True,
                                  return_exclusions=True)
    w("Exclusion reasons (Sleep Extension, `strict=True, for_phase_analysis=True`):\n")
    w(md_table(ex) + "\n")

    # ---- probe selection ------------------------------------------------------------
    sel = data.clock_probe_selection()
    sel.to_csv(config.TABLES_DIR / "selected_probes.csv", index=False)
    w("### Probe selection: one probe per gene\n")
    w("Default since issue #10: `select_probes(method=\"max_mean\")` keeps, for each gene, the "
      "probe with the **highest mean expression across all 438 samples**. It is used by "
      "`load_clock_genes()` and `collapse_probes_to_genes()`. Averaging probes "
      "(`collapse=\"mean\"`) is still available. Averaging would mix near-background probes "
      "into the signal (PER3 17478: mean log2 3.86, minimum 1.21). The rule ignores time, "
      "rhythmicity and genotype, so it cannot bias the rhythm or genotype tests. Saved to "
      "`results/tables/selected_probes.csv`.\n")
    w(md_table(sel) + "\n")

    # ---- series matrix --------------------------------------------------------------
    w("## 7. Series matrix (whole transcriptome)\n")
    if args.offline:
        w("_Skipped (`--offline`)._\n")
    else:
        path = data.download_series_matrix()
        expr, chars = data.load_expression_matrix(path, with_characteristics=True)
        v = expr.to_numpy()
        w(f"- Source: {config.SERIES_MATRIX_URL}")
        w(f"- File: {path.stat().st_size:,} bytes, sha256 `{sha256(path)[:16]}…`")
        w(f"- Shape: **{expr.shape[0]:,} probes × {expr.shape[1]} samples**; NaN: {int(np.isnan(v).sum())}")
        w(f"- Values: min {v.min():.2f}, median {np.median(v):.2f}, max {v.max():.2f}. This is "
          "consistent with log2 quantile-normalised Agilent signal (GEO: 'quantile-normalized "
          "using the R Bioconductor package limma'). A linear scale would span ~10^0–10^6.")
        w(f"- Probe IDs present in GPL15331 annotation: {int(expr.index.isin(annot.index).sum()):,}"
          f" / {len(expr):,}; with a gene symbol: "
          f"{int(annot.loc[expr.index, 'GENE_SYMBOL'].notna().sum()):,} probes → "
          f"{annot.loc[expr.index, 'GENE_SYMBOL'].nunique():,} unique genes")
        same_set = set(expr.columns) == set(meta.sample_id)
        w(f"- Sample IDs identical to metadata: {same_set}")
        sub = expr.loc[[p for _, p in pmap.values()], wide.sample_id].T
        sub.columns = list(pmap)
        maxdiff = float((sub.to_numpy() - wide[list(pmap)].to_numpy()).__abs__().max())
        w(f"- **Clock-gene CSV vs series matrix:** {len(pmap)} probes × {len(wide)} samples, "
          f"max |difference| = **{maxdiff:.3g}**")
        cm = meta.set_index("sample_id").loc[chars.index]
        agree = {
            "title": (chars.title == cm.title).all(),
            "circadianphase": (chars.circadianphase.astype(float) == cm.circadian_phase_h).all(),
            "timesampletaken": (chars.timesampletaken == cm.clock_time).all(),
            "hoursawake": (chars.hoursawake.astype(float) == cm.hours_awake).all(),
            "sleepprotocol": (chars.sleepprotocol == cm.sleep_condition).all(),
            "genotype": (chars["genotype/variation"].fillna(chars["genotype"])
                         .str.replace("\\", "/", regex=False) == cm.per3_genotype).all(),
        }
        w("- Matrix sample characteristics agree with metadata: "
          + ", ".join(f"{k}={v}" for k, v in agree.items()) + "\n")

    # ---- anomalies ----------------------------------------------------------------
    anom = timing_anomalies(meta)
    anom.to_csv(config.TABLES_DIR / "sample_anomalies.csv", index=False)
    w("## 8. Timing anomalies (for Part 2; not modified)\n")
    w("Checks per subject × condition: hours_awake = 7.5 + 3·(T−1); "
      "(clock_time − circadian_phase) mod 24 constant within ±1 h; "
      "clock-time gap between consecutive samples ≈ 3 h per timepoint step (±0.5 h). "
      "Saved to `results/tables/sample_anomalies.csv`.\n")
    w(md_table(anom) if len(anom) else "No anomalies found.")
    w("")
    w("`circadian_phase_h` takes only the values "
      + ", ".join(str(int(v)) for v in sorted(meta.circadian_phase_h.unique()))
      + " (3-h steps). It is a binned assignment, not a continuous per-sample measurement.\n")
    ref = ((meta.clock_time_h - meta.circadian_phase_h) % 24).rename("ref")
    per = meta.assign(ref=ref).groupby(["subject", "condition_code"]).ref.median().unstack()

    def hhmm(x: float) -> str:
        return f"{int(x):02d}:{round((x % 1) * 60):02d}"

    w("Implied clock time of circadian phase 0 (`clock_time_h − circadian_phase_h` mod 24, "
      "per-subject median): "
      + "; ".join(f"{c}: mean {hhmm(per[c].mean())} (range {hhmm(per[c].min())}–{hhmm(per[c].max())})"
                  for c in ("SE", "SR"))
      + ". Möller-Levet et al. (2013) report mean plasma-melatonin **midpoints** of 04:15 (control) "
      "and 05:01 (sleep restriction), consistent with phase 0 = melatonin midpoint (inference; the "
      "SI Methods definition was not checked).\n")

    text = "\n".join(out)
    (config.TABLES_DIR / "data_verification.md").write_text(text.rstrip() + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
